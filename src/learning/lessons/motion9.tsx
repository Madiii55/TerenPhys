function localized(value: Localized, language: Language): string {
  return typeof value === 'string' ? value : value[language]
}

/** Preserve selectable native text and semantic subscripts/superscripts. */
function notation(text: string): ReactNode {
  return text.split(/([_^]\{[^}]+\})/g).map((part, index) => {
    if (part.startsWith('_{')) return <sub key={index}>{part.slice(2, -1)}</sub>
    if (part.startsWith('^{')) return <sup key={index}>{part.slice(2, -1)}</sup>
    return part
  })
}

function LessonBlock({ block, language }: { block: Block; language: Language }) {
  if (block.kind === 'figure') {
    const caption = localized(block.caption, language)
    return <figure><img src={`/study/lessons/motion9-${language}-${block.name}.png`} alt={caption} loading="lazy" /><figcaption>{caption}</figcaption></figure>
  }
  if (block.kind === 'list') {
    const items = block.items.map((item, index) => <li key={index}>{notation(localized(item, language))}</li>)
    return block.ordered ? <ol>{items}</ol> : <ul>{items}</ul>
  }
  if (block.kind === 'table') {
    return <div className="study-lesson-table" tabIndex={0} role="region" aria-label={language === 'kk' ? 'Конспект кестесі. Жылжыту үшін бағыттауыш пернелерді пайдаланыңыз.' : 'Таблица конспекта. Для прокрутки используйте клавиши со стрелками.'}><table>
      <thead><tr>{block.headings.map((heading, index) => <th key={index} scope="col">{notation(localized(heading, language))}</th>)}</tr></thead>
      <tbody>{block.rows.map((row, rowIndex) => <tr key={rowIndex}>{row.map((cell, index) => <td key={index}>{notation(localized(cell, language))}</td>)}</tr>)}</tbody>
    </table></div>
  }
  const content = notation(localized(block.text, language))
  if (block.kind === 'equation') return <p className="study-lesson-equation">{content}</p>
  if (block.kind === 'label') return <p><strong>{content}</strong></p>
  return <p>{content}</p>
}

